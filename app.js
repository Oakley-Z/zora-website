let currentLang = detectLanguage();

function getSavedLanguage() {
  try {
    return localStorage.getItem("zoraLang");
  } catch {
    return "";
  }
}

function saveLanguage(lang) {
  try {
    localStorage.setItem("zoraLang", lang);
  } catch {
    // Language still changes for the current page when storage is unavailable.
  }
}

function detectLanguage() {
  const saved = getSavedLanguage();
  if (saved && translations[saved]) return saved;
  const timezone = Intl.DateTimeFormat().resolvedOptions().timeZone || "";
  const languages = navigator.languages || [navigator.language || ""];
  const joined = languages.join(" ").toLowerCase();
  if (timezone.includes("Hong_Kong") || joined.includes("zh-hk") || joined.includes("zh-tw")) return "zh-HK";
  if (timezone.includes("Shanghai") || joined.includes("zh-cn") || joined.includes("zh")) return "zh-CN";
  return "en";
}

function escapeHtml(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function renderAboutText() {
  const node = document.querySelector("#aboutAnimated");
  const current = translations[currentLang];
  node.innerHTML = current.aboutParagraphs
    .map((paragraph) => {
      const escaped = escapeHtml(paragraph);
      const highlight = current.aboutHighlight ? escapeHtml(current.aboutHighlight) : "";
      const body = highlight ? escaped.replace(highlight, `<strong>${highlight}</strong>`) : escaped;
      return `<p>${body}</p>`;
    })
    .join("") + `<strong class="belief-line">${escapeHtml(current.aboutQuote)}</strong>`;
}

function applyLanguage(lang) {
  currentLang = translations[lang] ? lang : "en";
  saveLanguage(currentLang);
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    const value = translations[currentLang][key];
    if (!value) return;
    node.textContent = value;
  });
  renderAboutText();
  document.querySelectorAll(".lang-button").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === currentLang);
  });
  updateAnimatedText();
}

function renderMarquee() {
  const rows = [
    document.querySelector("#marqueeRowOne"),
    document.querySelector("#marqueeRowTwo"),
  ];
  rows.forEach((row, index) => {
    const source = index === 0 ? marqueeImages.slice(0, 5) : marqueeImages.slice(3);
    row.innerHTML = Array.from({ length: 3 })
      .flatMap(() => source)
      .map((src) => `<img src="${src}" alt="" loading="lazy" />`)
      .join("");
  });
}

function bindReveal() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) entry.target.classList.add("visible");
      });
    },
    { threshold: 0.08 }
  );
  document.querySelectorAll(".fade-in, .reveal").forEach((node, index) => {
    node.style.transitionDelay = `${Math.min(index * 0.05, 0.3)}s`;
    observer.observe(node);
  });
}

function updateMarquee() {
  const section = document.querySelector(".marquee-section");
  const rect = section.getBoundingClientRect();
  const offset = (window.scrollY + window.innerHeight - section.offsetTop) * 0.3;
  document.querySelectorAll(".marquee-row").forEach((row) => {
    const direction = row.dataset.direction;
    const amount = direction === "right" ? offset - 200 : -(offset - 200);
    row.style.transform = `translate3d(${amount}px, 0, 0)`;
  });
  if (rect.bottom < 0 || rect.top > window.innerHeight) return;
}

function updateAnimatedText() {
  const paragraph = document.querySelector("#aboutAnimated");
  if (!paragraph) return;
  const rect = paragraph.getBoundingClientRect();
  const start = window.innerHeight * 0.82;
  const end = window.innerHeight * 0.2;
  const progress = Math.max(0, Math.min(1, (start - rect.top) / (start - end)));
  const chars = paragraph.querySelectorAll("span");
  chars.forEach((span, index) => {
    const charProgress = index / Math.max(chars.length - 1, 1);
    const visible = progress * 1.25 - charProgress * 0.55;
    span.style.opacity = String(Math.max(0.22, Math.min(1, visible)));
  });
}

function updateProjectStack() {
  const cards = document.querySelectorAll(".stack-card");
  cards.forEach((card, index) => {
    const rect = card.getBoundingClientRect();
    const progress = Math.max(0, Math.min(1, -rect.top / Math.max(rect.height, 1)));
    const targetScale = 1 - (cards.length - 1 - index) * 0.03;
    const scale = 1 - progress * (1 - targetScale);
    card.style.transform = `scale(${scale})`;
  });
}

function bindMagnet() {
  const portrait = document.querySelector(".magnet-target");
  if (!portrait) return;
  const strength = 3;
  const padding = 150;
  window.addEventListener("mousemove", (event) => {
    const rect = portrait.getBoundingClientRect();
    const centerX = rect.left + rect.width / 2;
    const centerY = rect.top + rect.height / 2;
    const within =
      event.clientX > rect.left - padding &&
      event.clientX < rect.right + padding &&
      event.clientY > rect.top - padding &&
      event.clientY < rect.bottom + padding;
    if (!within) {
      portrait.style.transition = "transform 0.6s ease-in-out";
      portrait.style.transform = "translateX(-50%)";
      return;
    }
    const x = (event.clientX - centerX) / strength;
    const y = (event.clientY - centerY) / strength;
    portrait.style.transition = "transform 0.3s ease-out";
    portrait.style.transform = `translateX(-50%) translate3d(${x}px, ${y}px, 0)`;
  });
}

function bindCursor() {
  const cursor = document.querySelector(".cursor-light");
  window.addEventListener("pointermove", (event) => {
    cursor.style.opacity = "1";
    cursor.style.transform = `translate(${event.clientX - 11}px, ${event.clientY - 11}px)`;
  });
  window.addEventListener("pointerleave", () => {
    cursor.style.opacity = "0";
  });
}

function showToast(message) {
  const toast = document.querySelector("#toast");
  toast.textContent = message;
  toast.classList.add("show");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => toast.classList.remove("show"), 2400);
}

function bindEvents() {
  document.querySelectorAll(".lang-button").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang));
  });

  document.querySelector("#copyEmail").addEventListener("click", async () => {
    try {
      await navigator.clipboard.writeText(email);
      showToast(translations[currentLang].copied);
    } catch {
      showToast(email);
    }
  });

  window.addEventListener(
    "scroll",
    () => {
      updateMarquee();
      updateAnimatedText();
      updateProjectStack();
    },
    { passive: true }
  );
  window.addEventListener("resize", updateProjectStack);
}

function init() {
  renderMarquee();
  bindEvents();
  bindReveal();
  bindMagnet();
  bindCursor();
  applyLanguage(currentLang);
  updateMarquee();
  updateProjectStack();
}

init();
